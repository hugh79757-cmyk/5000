def get_weighted_random_sigungu(exclude_sigungus: set | None = None) -> tuple:
    """가중치 기반 랜덤 시군구 선택.
    exclude_sigungus: 최근 발행된 시군구명 set (제외 대상).
    반환: (areaCode, sigunguCode, display_name)
    """
    import random
    pool = FOOD_AREA_SIGUNGU_WEIGHTED
    if exclude_sigungus:
        pool = [x for x in pool if x[2] not in exclude_sigungus]
    if not pool:
        pool = FOOD_AREA_SIGUNGU_WEIGHTED  # 전체 소진 시 제한 해제
    weights = [x[3] for x in pool]
    chosen = random.choices(pool, weights=weights, k=1)[0]
    return chosen[0], chosen[1], chosen[2]


def find_by_sigungu_name(name: str):
    """시군구명으로 (areaCode, sigunguCode, display_name) 찾기
    '강릉시' 또는 '강릉' 둘 다 매칭
    """
    for entry in FOOD_AREA_SIGUNGU:
        _, _, display = entry
        if display == name or display.startswith(name) or name.startswith(display):
            return entry
    # 접두사 매칭 (예: '수성' → '수성구')
    for entry in FOOD_AREA_SIGUNGU:
        _, _, display = entry
        if display.startswith(name) or name in display:
            return entry
    return None


# ── 지역명 검증 집합 (태그용) ──────────────────────────────────
_REGION_NAME_SET = {name for _, _, name in FOOD_AREA_SIGUNGU}


def validate_display_region(display_region: str) -> str | None:
    """display_region(예: '강원도 강릉시')이 알려진 지역명인지 검증.
    유효하면 원래 문자열 반환, 무효하면 None 반환 (태그 제거).
    """
    if not display_region or not display_region.strip():
        return None
    parts = display_region.split()
    for p in parts:
        if p in _REGION_NAME_SET:
            return display_region
    return None
