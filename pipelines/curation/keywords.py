_POOL_DB_PATH = None  # 테스트용 override (None이면 data/curation.db 자동 해석)


def _get_from_pool(blog_id):
    """keyword_pool에서 미사용 키워드 1개 조회. 있으면 used 마킹 후 반환, 없으면 None.

    우선순위: blog_id 전용 → blog_id=''(범용). 격리 키워드는 스킵.
    어떤 오류가 나도 None 반환 — KEYWORD_MAP fallback 절대 차단 안 함.
    """
    try:
        import sqlite3
        from pathlib import Path
        from pipelines.curation.keyword_health import KeywordHealthStore

        db_path = _POOL_DB_PATH or str(Path(__file__).resolve().parents[2] / "data" / "curation.db")
        conn = sqlite3.connect(db_path)
        row = conn.execute(
            "SELECT id, keyword FROM keyword_pool WHERE used=0 AND blog_id=? ORDER BY id LIMIT 1",
            (blog_id,),
        ).fetchone()
        if row is None:
            row = conn.execute(
                "SELECT id, keyword FROM keyword_pool WHERE used=0 AND blog_id='' ORDER BY id LIMIT 1"
            ).fetchone()
        if row is None:
            conn.close()
            return None
        pool_id, kw = int(row[0]), row[1]
        try:
            quarantined = KeywordHealthStore(db_path).is_quarantined(blog_id, kw)
        except Exception:
            quarantined = False  # keyword_health 미생성 등 — fail-open (하류 게이트가 최종 판단)
        if quarantined:
            conn.execute("UPDATE keyword_pool SET used=1, used_at=datetime('now') WHERE id=?", (pool_id,))
            conn.commit()
            conn.close()
            return None
        conn.execute("UPDATE keyword_pool SET used=1, used_at=datetime('now') WHERE id=?", (pool_id,))
        conn.commit()
        conn.close()
        return kw
    except Exception:
        return None


