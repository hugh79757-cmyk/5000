# 긴 키부터 정렬
_ORDER = sorted(MAPPING.keys(), key=len, reverse=True)
_CJK = re.compile(r"[\u4e00-\u9fff]")


def replace_cjk(text: str) -> str:
    for k in _ORDER:
        if k in text:
            text = text.replace(k, MAPPING[k])
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    bases = ["appliance", "baby", "fitness", "interior", "laptop", "health",
             "pet", "kitchen", "beauty", "camping", "massage", "car",
             "homeappliance", "golf", "bike"]
    total_files = 0
    total_chars = 0
    for b in bases:
        d = f"/Users/twinssn/Projects/CUAP/{b}-hugo/content/posts"
        for root, _, fs in os.walk(d):
            for fn in fs:
                if fn != "index.md":
                    continue
                if fn.endswith((".bak", ".bak2", ".bak-2703")):
                    continue
                f = os.path.join(root, fn)
                txt = open(f, encoding="utf-8").read()
                if not _CJK.search(txt):
                    continue
                new = replace_cjk(txt)
                remaining = len(_CJK.findall(new))
                total_files += 1
                total_chars += remaining
                if args.dry_run:
                    print(f"[DRY] {f}: 잔여 CJK {remaining}자")
                else:
                    open(f, "w", encoding="utf-8").write(new)
                    print(f"[WRITE] {f}: 잔여 CJK {remaining}자")
    print(f"\n총 처리 파일: {total_files}건, 잔여 CJK: {total_chars}자")


if __name__ == "__main__":
    main()
